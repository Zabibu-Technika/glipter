import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, resolve, sep } from "node:path";

const root = resolve(process.cwd());
const skipDirs = new Set(["node_modules", ".git", ".vercel", "datasets", "scripts", "tests", "docs", "coverage", ".tmp"]);
const skipFiles = new Set(["sw.js", "package.json", "package-lock.json", "vercel.json"]);
const includeExt = new Set([".html", ".js", ".mjs", ".css", ".json", ".webmanifest", ".svg", ".png", ".ico", ".wasm", ".data", ".tflite", ".binarypb", ".task"]);

function walk(dir, files = []) {
  for (const entry of readdirSync(dir)) {
    if (skipDirs.has(entry)) continue;
    const full = join(dir, entry);
    const info = statSync(full);
    if (info.isDirectory()) {
      walk(full, files);
    } else if (!skipFiles.has(entry)) {
      const ext = entry.includes(".") ? entry.slice(entry.lastIndexOf(".")) : "";
      if (includeExt.has(ext)) files.push(full);
    }
  }
  return files;
}

const files = walk(root)
  .map((file) => relative(root, file).split(sep).join("/"))
  .filter((file) => !file.startsWith("datasets/") && !file.startsWith("scripts/") && !file.startsWith("docs/"))
  .sort();

const precache = ["./index.html", ...files.filter((file) => file !== "index.html").map((file) => `./${file}`)];
const unique = [...new Set(precache)];

const source = `/* Glipter service worker - generated by scripts/build-sw.mjs */
const CACHE = "glipter-v3.1.0";
const PRECACHE = ${JSON.stringify(unique, null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    const total = PRECACHE.length;
    let done = 0;
    const failed = [];
    const batchSize = 6;

    // Cache in small batches so one slow or missing asset cannot block the
    // whole install. Report progress to the page for the offline badge.
    for (let start = 0; start < PRECACHE.length; start += batchSize) {
      const batch = PRECACHE.slice(start, start + batchSize);
      const results = await Promise.allSettled(batch.map(async (url) => {
        await cache.add(url);
        done += 1;
      }));
      results.forEach((result, index) => {
        if (result.status === "rejected") failed.push(batch[index]);
      });
      const clients = await self.clients.matchAll({ includeUncontrolled: true });
      clients.forEach((client) => client.postMessage({
        type: "GLIPTER_PRECACHE",
        done,
        total,
        failed: failed.length,
      }));
    }

    if (failed.length) console.warn("Glipter precache incomplete:", failed);
    await self.skipWaiting();
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  // SPA navigation: always fall back to the cached shell.
  if (request.mode === "navigate") {
    event.respondWith(
      caches.match("./index.html").then((cached) => cached || fetch(request)),
    );
    return;
  }

  event.respondWith(
    caches.match(request).then((cached) => {
      if (cached) return cached;
      return fetch(request).then((response) => {
        if (response.ok) {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put(request, copy));
        }
        return response;
      }).catch(() => caches.match("./index.html"));
    }),
  );
});
`;

writeFileSync(join(root, "sw.js"), source);
console.log(`Wrote sw.js with ${unique.length} precached entries.`);
for (const file of unique) console.log(`  ${file}`);
